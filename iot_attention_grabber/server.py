from fastapi import FastAPI, WebSocket
from fastapi.requests import Request
from fastapi.responses import HTMLResponse
from fastapi.staticfiles import StaticFiles
import uvicorn
import os
import threading
import ctypes

app = FastAPI()
connected_clients = []

# =====================================================================
# Directory Configuration
# =====================================================================
# Capture the absolute path to prevent errors when executed from a .bat file
BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DIST_DIR = os.path.join(BASE_DIR, "frontend-IoT", "dist")
SRC_DIR = os.path.join(BASE_DIR, "frontend-IoT", "src")

# Mount the React assets folder (typically contains JS and CSS files)
app.mount("/assets", StaticFiles(directory=os.path.join(DIST_DIR, "assets")), name="assets")

# Mount the public files (such as audio or images) located in the dist root
app.mount("/static", StaticFiles(directory=DIST_DIR), name="static")


# =====================================================================
# Audio Player Setup
# =====================================================================
# Plays audio directly on the host machine rather than through the browser.
# Uses winmm.dll (native Windows library) via ctypes, eliminating the need 
# for third-party pip packages. Ideal for offline kiosk devices.

AUDIO_PATHS = {
    "in": os.path.join(SRC_DIR, "audio_in.mp3"),
    "out": os.path.join(SRC_DIR, "audio_out.mp3"),
}

_MCI_ALIAS = "churchGreetingAudio"


def play_audio(status: str):
    """
    Plays the corresponding audio file based on the status using the 
    Windows Media Control Interface. 
    Runs on a separate thread to prevent blocking the FastAPI/uvicorn event loop.
    """
    path = AUDIO_PATHS.get(status)
    
    if not path:
        return
    if not os.path.exists(path):
        print(f"[AUDIO] File not found: {path}")
        return

    # Close the previous instance (if still open) so the alias can be reused
    ctypes.windll.winmm.mciSendStringW(f"close {_MCI_ALIAS}", None, 0, None)

    try:
        ctypes.windll.winmm.mciSendStringW(
            f'open "{path}" type mpegvideo alias {_MCI_ALIAS}', None, 0, None
        )
        ctypes.windll.winmm.mciSendStringW(f"play {_MCI_ALIAS}", None, 0, None)
    except Exception as e:
        print(f"[AUDIO] Failed to play audio: {e}")


# =====================================================================
# API Endpoints & WebSockets
# =====================================================================

@app.get("/")
async def get_index():
    """Reads and serves the index.html generated by the Vite React build process."""
    file_path = os.path.join(DIST_DIR, "index.html")
    with open(file_path, "r", encoding="utf-8") as f:
        return HTMLResponse(f.read())


@app.websocket("/ws")
async def websocket_endpoint(websocket: WebSocket):
    """Handles WebSocket connections for real-time UI updates."""
    await websocket.accept()
    connected_clients.append(websocket)
    try:
        while True:
            await websocket.receive_text()
    except Exception:
        connected_clients.remove(websocket)


@app.post("/")
async def receive_data(request: Request):
    """Receives sensor data from the ESP32 and triggers audio and UI updates."""
    data = await request.json()
    status = data.get("status")
    distance = data.get("distance")

    print(f"\n[{status.upper()}] Person detected at distance: {distance} cm")

    # Play audio directly on this device (runs on a separate, non-blocking thread)
    threading.Thread(target=play_audio, args=(status,), daemon=True).start()

    # Broadcast the status to the UI to update the on-screen animations and text
    for client in connected_clients:
        await client.send_json({"status": status})

    return {"message": "Signal received successfully!"}


if __name__ == "__main__":
    print("FastAPI + React Build server is running!")
    uvicorn.run(app, host="0.0.0.0", port=8001)